const assert=require('node:assert/strict');
const E=require('../gameday-engine.js');
const now=Date.parse('2026-11-07T15:00:00Z');
const leg=(id,team,extra={})=>({id,team,home:team,away:'away-'+id,market:'moneyline',date:'2026-11-07T20:00:00Z',timeValid:true,quoteAt:'2026-11-07T13:00:00Z',odds:150,p:.65,provider:'Book A',...extra});
assert.equal(E.day('2026-11-07T02:00:00Z'),'2026-11-06','after-midnight UTC games stay on Eastern date');
assert.equal(E.day('2026-11-01T05:30:00Z'),'2026-11-01','DST transition');
assert.deepEqual(E.dates([{date:'2026-11-06T12:00Z'},{date:'2026-11-08T12:00Z'},{date:'2026-11-07T19:00Z'}],now),['2026-11-07','2026-11-08','2026-11-06']);
assert.equal(E.half(13.4),13.5);assert.equal(E.half(27.01),27);assert.equal(E.half(-4.9),-5);
assert.equal(E.available(null,now),false);
assert.equal(E.available(leg('1','a'),now),true);
assert.equal(E.available(leg('1','a',{date:new Date(now).toISOString()}),now),false);
assert.equal(E.available(leg('1','a',{quoteAt:'2026-11-01T12:00Z'}),now),false);
assert.equal(E.available(leg('1','a',{quoteAt:'2026-11-08T12:00Z'}),now),false);
assert.equal(E.available(leg('1','a',{reviewRequired:true}),now),false);
assert.equal(E.available(leg('1','a',{odds:null}),now),false);
assert.equal(E.available(leg('1','a',{timeValid:false}),now),false);
assert.ok(E.conflict([leg('1','a')],leg('1','b')));
assert.ok(E.conflict([leg('1','a')],leg('2','a')));
assert.ok(E.conflict([leg('1','a')],leg('2','b',{provider:'Book B'})));
assert.equal(E.conflict([leg('1','a')],leg('2','b')),null);
const math=E.ticketMath([leg('1','a',{odds:-200}),leg('2','b',{odds:200})],10);
assert.equal(math.return,45);assert.equal(math.profit,35);assert.equal(math.odds,'+350');
assert.equal(E.ticketMath([],10).return,null);assert.equal(E.ticketMath([leg('1','a')],-10).return,null);
const auto=E.suggest([leg('1','a'),leg('2','b',{p:.8}),leg('3','c',{p:.6}),leg('4','d',{p:.99,reviewRequired:true}),leg('5','e',{p:.99,odds:-10000})],2,now);
assert.deepEqual(auto.map(l=>l.id),['2','1']);
assert.deepEqual(E.suggest([leg('1','a')],2,now),[]);
const games=[{id:'1',home:'a',away:'away-1',done:true,hs:30,as:20},{id:'2',home:'b',away:'away-2',done:true,hs:20,as:10}];
const ticket={stake:10,legs:[leg('1','a'),leg('2','b')]};
assert.equal(E.settle(ticket,games).result,'win');assert.equal(E.settle(ticket,games).returned,62.5);
assert.equal(E.settle(ticket,games.slice(0,1)).result,'pending');assert.equal(E.settle(ticket,[]).returned,null);
assert.equal(E.settle(ticket,[games[0],{...games[1],hs:3}]).result,'loss');
assert.equal(E.settle(ticket,[games[0],{...games[1],done:false,status:'STATUS_CANCELED'}]).returned,25);
assert.equal(E.gradeLeg({...leg('1','a'),market:'spread',line:-10},games[0]),'push');
assert.equal(E.gradeLeg({...leg('1','a'),market:'total',side:'over',line:50},games[0]),'push');
assert.equal(E.gradeLeg(leg('1','a'),{...games[0],done:false,status:'STATUS_POSTPONED'}),'pending');
assert.deepEqual(E.restore([{id:'x',stake:10,legs:[{id:'1',odds:150}]}]),[]);
assert.equal(E.restore([{id:'x',...ticket}]).length,1);
console.log('Game-day calendar, quote eligibility, ticket selection and settlement checks passed');
// Sportsbook-style selection and persistent draft behavior.
const twelve=Array.from({length:12},(_,i)=>leg(String(i),'team-'+i,{p:.9-i*.01}));
assert.equal(E.conflict(twelve.slice(0,11),twelve[11]),null);
assert.match(E.conflict(twelve,leg('13','team-13')),/12/);
assert.equal(E.toggle(twelve,twelve[0]).legs.length,11,'tapping selected odds removes the pick');
const replacement=E.toggle(twelve,leg('0','other-side'));
assert.equal(replacement.legs.length,12,'opposite team replaces the same-game pick');
assert.equal(replacement.legs.at(-1).team,'other-side');
assert.equal(E.restoreDraft({legs:twelve,stake:25}).legs.length,12);
assert.deepEqual(E.restoreDraft({legs:[],stake:25}),{legs:[],stake:10});
assert.equal(E.suggest(twelve,12,now).length,12);
assert.equal(E.suggest(twelve,13,now).length,0);
const large=Array.from({length:100},(_,i)=>leg('large-'+i,'large-team-'+i,{p:.95-i*.001}));
assert.deepEqual(E.suggest(large,12,now).map(l=>l.id),large.slice(0,12).map(l=>l.id));
console.log('12-leg selection, toggle, replacement, draft restore and bounded auto-pick checks passed');
const spread=leg('s','home',{market:'spread',line:-3.5,odds:-110,p:null});
const total=leg('t','home-t',{market:'total',side:'over',line:47.5,odds:-105,p:null});
assert.equal(E.restore([{id:'mixed',stake:10,legs:[spread,total]}]).length,1);
assert.equal(E.ticketMath([spread,total],10).all,null,'do not invent total probability');
assert.ok(E.ticketMath([spread,total],10).return>0);
assert.equal(E.toggle([total],{...total,side:'under'}).legs[0].side,'under');
assert.ok(E.toggle([spread],{...spread,market:'total',side:'over'}).error,'same-game correlations need SGP pricing');
assert.equal(E.gradeLeg(spread,{id:'s',home:'home',away:'away-s',done:true,hs:24,as:20}),'win');
assert.equal(E.gradeLeg(total,{id:'t',home:'home-t',away:'away-t',done:true,hs:24,as:24}),'pending');
assert.equal(E.gradeLeg(total,{id:'t',home:'home-t',away:'away-t',done:true,hs:28,as:21}),'win');
const L=require('../live-scores.js');
assert.equal(L.interval,600000);
const event=(state,completed,homeScore,awayScore)=>({events:[{id:'live',date:'2026-11-07T20:00:00Z',competitions:[{status:{type:{state,completed,shortDetail:'3rd 7:05'}},competitors:[{homeAway:'home',score:homeScore,team:{id:'h',displayName:'Home'}},{homeAway:'away',score:awayScore,team:{id:'a',displayName:'Away'}}]}]}]});
assert.equal(L.parse(event('pre',false,'0','0'))[0].homeScore,null,'never display zero as an upcoming actual score');
assert.equal(L.parse(event('in',false,'14','7'))[0].homeScore,14);
assert.equal(L.parse(event('post',true,'21','17'))[0].done,true);
assert.equal(L.parse(event('in',false,null,'7'))[0].homeScore,null);
assert.throws(()=>L.parse({}),/Invalid/);
console.log('Mixed-market drafts, grading, missing probabilities and live-score parsing checks passed');
