const assert=require('node:assert/strict');
const {fresh,rate,formulate,assess,dataStale,feedStatus,readiness}=require('../sniper.js');
const now=Date.parse('2026-11-06T12:00:00Z');
const q={bookKey:'a',side:'Over',line:50,updatedAt:'2026-11-06T11:00:00Z'};
const p={id:'1',team:'a',matchupFactor:1,quotes:[q],samples:[10,50,60,70,80,90].map((value,i)=>({gameId:String(i),value}))};
assert.deepEqual(rate(p,q),{wins:4,pushes:1,n:6});
assert.equal(fresh({...q,updatedAt:'2026-11-05T11:00:00Z'},now),false);
assert.equal(fresh({...q,updatedAt:'2026-11-07T11:00:00Z'},now),false);
const g={date:'2026-11-07T12:00:00Z',players:[p,{...p,id:'2'}]};
assert.equal(formulate(g,now).hits,4); // Shared outcomes, not .667 squared.
assert.equal(formulate({...g,reviewRequired:true},now),null);
assert.equal(formulate({...g,date:'2026-11-05T12:00:00Z'},now),null);
assert.equal(formulate({...g,players:[p,{...p,id:'2',team:'b'}]},now),null);
assert.equal(formulate({...g,players:[p,{...p,id:'2',quotes:[{...q,bookKey:'b'}]}]},now),null);
assert.equal(formulate({...g,players:[p,p]},now),null);
const data={refreshRunId:'r1',inputRetrievedAt:'2026-11-06T11:00:00Z',lineStatus:'connected'};
assert.equal(dataStale(data,'r1',now),false);
assert.equal(dataStale(data,'r2',now),true);
assert.equal(dataStale({...data,inputRetrievedAt:'invalid'},'r1',now),true);
assert.equal(dataStale({...data,inputRetrievedAt:'2026-11-07T11:00:00Z'},'r1',now),true);
assert.equal(dataStale({...data,inputRetrievedAt:'2026-11-04T11:00:00Z'},'r1',now),true);
assert.equal(readiness(g,data,'r1',now).ticket.hits,4);
assert.equal(readiness(g,data,'r2',now).code,'stale');
assert.equal(assess({...g,reviewRequired:true},now).code,'review');
assert.equal(assess({...g,date:'2026-11-06T11:00:00Z'},now).code,'started');
const noLines={...g,players:g.players.map(p=>({...p,quotes:[]}))};
assert.equal(assess(noLines,now).code,'no_quotes');
assert.equal(assess({...g,players:g.players.map(p=>({...p,quotes:[{...q,updatedAt:'2026-11-05T11:00:00Z'}]}))},now).code,'expired');
assert.equal(assess({...g,players:g.players.map(p=>({...p,samples:p.samples.slice(0,5)}))},now).code,'history');
assert.equal(assess({...g,players:g.players.map(p=>({...p,quotes:[{...q,line:100}]}))},now).code,'threshold');
assert.equal(assess({...g,players:[p,{...p,id:'2',team:'b'}]},now).code,'pairing');
assert.equal(assess({...g,players:[p,{...p,id:'2',samples:p.samples.map(s=>({...s,gameId:'other'+s.gameId}))}]},now).code,'shared_history');
const exhausted={...data,lineStatus:'provider_error',providerError:{code:'OUT_OF_USAGE_CREDITS',httpStatus:401}};
assert.match(feedStatus(exhausted).message,/run out of usage credits/);
assert.doesNotMatch(feedStatus(exhausted).message,/key is needed/);
assert.match(readiness(noLines,exhausted,'r1',now).message,/credits/);
assert.equal(readiness(noLines,exhausted,'r1',now).ticket,null);
// A partial provider failure may retain valid quotes, but never extends their life.
assert.equal(readiness(g,exhausted,'r1',now).ticket.hits,4);
assert.equal(readiness(g,exhausted,'r1',now+6*3600000).code,'expired');
assert.match(feedStatus({...data,lineStatus:'not_connected'}).message,/connect The Odds API/);
assert.match(feedStatus({...exhausted,providerError:{code:'INVALID_KEY'}}).message,/rejected/);
assert.match(feedStatus({...exhausted,providerError:{code:'EXCEEDED_FREQ_LIMIT'}}).message,/slow down/);
assert.match(feedStatus({...exhausted,providerError:{code:'NETWORK_ERROR',message:'secret-do-not-render'}}).message,/returned an error/);
assert.doesNotMatch(JSON.stringify(feedStatus({...exhausted,providerError:{code:'secret-do-not-render'}})),/secret-do-not-render/);
console.log('Sniper freshness, pushes, correlated samples and ticket restrictions passed');
console.log('Sniper provider errors and per-game SGP readiness passed');
