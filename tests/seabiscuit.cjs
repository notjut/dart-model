const assert=require('node:assert/strict');
const {eligibleQuote,isUpsetPick,isSeabiscuit,picks}=require('../seabiscuit.js');
const now=Date.parse('2026-11-03T14:00:00Z');
const g={date:'2026-11-07T17:00:00Z',done:false};
const o={date:g.date,retrievedAt:'2026-11-03T12:00:00Z',timeValid:true,state:'pre',homeMoneyline:170,awayMoneyline:-300};
const row={odds:170,p:.56,margin:2.5,side:'home',o};
assert.equal(isSeabiscuit(row),true,'+170 is included');
assert.equal(isSeabiscuit({...row,odds:169}),false,'Below +170 is not a Seabiscuit');
assert.equal(isUpsetPick({...row,odds:169}),true,'Smaller underdog remains an upset pick');
assert.equal(isSeabiscuit({...row,odds:425,p:.3,margin:-8}),false,'Upset-watch is not a predicted outright win');
assert.equal(isSeabiscuit({...row,p:.5,margin:0}),false,'An even forecast is not an outright selection');
assert.equal(isSeabiscuit({...row,odds:-170}),false,'Favorite moneylines are not Seabiscuit plays');
assert.equal(isSeabiscuit({...row,side:'away',o:{homeMoneyline:-300,awayMoneyline:170}}),true,'Away underdogs qualify');
assert.equal(isUpsetPick({...row,o:{...o,awayMoneyline:100}}),false,'Do not label a dog with an ambiguous opposite price');
assert.equal(eligibleQuote(o,g,now),true);
assert.equal(eligibleQuote({...o,retrievedAt:'invalid'},g,now),false);
assert.equal(eligibleQuote({...o,retrievedAt:'2026-11-03T15:00:00Z'},g,now),false);
assert.equal(eligibleQuote({...o,retrievedAt:'2026-10-30T12:00:00Z'},g,now),false);
assert.equal(eligibleQuote({...o,state:'post'},g,now),false);
assert.equal(eligibleQuote(o,{...g,done:true},now),false);
assert.equal(eligibleQuote(o,{...g,date:'2026-11-03T13:00:00Z'},now),false,'Earlier rescheduled kickoff blocks expired pick');
assert.equal(eligibleQuote({...o,homeMoneyline:null},g,now),false);
assert.equal(eligibleQuote({...o,timeValid:false},g,now),false);
assert.equal(eligibleQuote({...o,date:'invalid'},g,now),false);
assert.equal(picks([{...row,odds:160,p:.8},row])[0].odds,170,'Seabiscuit plays headline ahead of regular upset picks');
console.log('Seabiscuit threshold, outright selection, and quote safeguards passed');
